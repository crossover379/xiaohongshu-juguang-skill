def get_advanced_diagnosis(dashboard_data, industry="旅游/酒旅"):
    """基于进阶知识库进行深度诊断"""
    diagnosis = []
    
    # 提取关键数据
    today = dashboard_data.get('today_data', {})
    summary = dashboard_data.get('campaign_summary', {})
    budget = dashboard_data.get('account_budget', {})
    
    cost = today.get('total_cost', 0)
    ctr = today.get('ctr', 0)
    cpc = today.get('cpc', 0)
    impressions = today.get('impression', 0)
    clicks = today.get('click', 0)
    active = summary.get('active', 0)
    balance = budget.get('available_balance_yuan', 0)
    daily_budget = budget.get('budget_yuan', 0)
    
    # 1. 账户健康度评估
    health_status = {}
    if ctr > 0:
        if ctr >= 5:
            health_status['CTR'] = '优秀'
        elif ctr >= 3:
            health_status['CTR'] = '良好'
        else:
            health_status['CTR'] = '需优化'
    
    if health_status:
        diagnosis.append({
            "type": "账户健康度评估",
            "level": "📊",
            "status": health_status,
            "insight": f"CTR: {ctr:.1f}%",
        })
    
    # 2. 计划结构诊断
    if active > 0:
        if active > 20:
            diagnosis.append({
                "type": "计划结构问题",
                "level": "⚠️",
                "insight": f"投放中计划{active}个，计划过于分散",
                "expert_advice": "根据高级账户操作技巧：\n1. 测试期：1个广告组+5-10条不同素材\n2. 放量期：3-5个广告组+每个广告组2-3条优质素材\n3. 收割期：1个广告组+1条爆款素材",
                "action": "建议暂停低效计划，集中预算到2-3个核心计划",
            })
    
    # 3. 预算分配诊断
    if daily_budget > 0:
        budget_usage = cost / daily_budget * 100
        if budget_usage < 30:
            diagnosis.append({
                "type": "预算利用不足",
                "level": "⚠️",
                "insight": f"今日消耗{cost:.1f}元，仅占日预算{budget_usage:.0f}%",
                "expert_advice": "根据预算分配黄金法则：\n1. 通用比例：30%测试+70%放量\n2. 集中火力原则：2-3个计划消耗80%预算\n3. 动态倾斜：实时向高ROI场域转移预算",
                "action": "检查素材质量，优化出价，提高预算利用率",
            })
    
    # 4. 余额预警
    if balance < 200 and balance > 0:
        diagnosis.append({
            "type": "余额预警",
            "level": "💰",
            "insight": f"余额{balance:.0f}元，按当前消耗预计可用{balance/cost:.1f}天",
            "expert_advice": "余额不足会导致：\n1. 系统自动压低出价\n2. 流量质量下降\n3. 转化成本上升",
            "action": "尽快充值，保持账户余额充足",
        })
    
    # 5. 行业专属建议
    diagnosis.append({
        "type": "行业策略建议",
        "level": "💡",
        "insight": f"基于{industry}行业最佳实践",
        "expert_advice": f"行业策略：\n1. 最佳投放时段：19:00-24:00\n2. 推荐转化方式：私信咨询、预订链接\n3. 素材特点：风景实拍、住宿体验、行程攻略\n4. 关键词策略：目的地+品类+需求",
        "action": f"根据{industry}行业特点调整投放策略",
    })
    
    return diagnosis


def format_advanced_diagnosis(diagnosis):
    """格式化深度诊断"""
    if not diagnosis:
        return "暂无诊断结果"
    
    report = f"🧠 顶级投手深度诊断\n{'═'*45}\n\n"
    
    for item in diagnosis:
        report += f"{item['level']} {item['type']}\n"
        report += f"{'─'*40}\n"
        report += f"📊 {item['insight']}\n\n"
        
        if 'status' in item:
            report += "健康度：\n"
            for key, value in item['status'].items():
                report += f"  • {key}: {value}\n"
            report += "\n"
        
        if 'expert_advice' in item:
            report += f"💡 专家解读：\n{item['expert_advice']}\n\n"
        
        if 'action' in item:
            report += f"🎯 建议操作：{item['action']}\n\n"
    
    return report


